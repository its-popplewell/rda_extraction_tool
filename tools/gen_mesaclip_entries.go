// gen_mesaclip_entries prints dataset.toml entries for MESACLIP members,
// one per (period, member, variable). Temporary: replace with a request-level
// `case` field in RDAExtension later.
//
// usage: go run gen_mesaclip_entries.go 004 005 ... > mesaclip_entries.toml
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const gridFile = "/glade/work/jackscheffel/regrid/ne120_grid.nc"

type period struct {
	datasetPrefix string // dataset name is <datasetPrefix>_<member>
	archive       string // archive key in config.toml
	root          string // archive path, used to find the case directory
	compset       string // appears in the case directory name
	label         string
}

var periods = []period{
	{"mesaclip_hist", "mesaclip_hist", "/glade/campaign/collections/rda/data/d651007", "BHISTC5", "historical"},
	{"mesaclip_rcp", "mesaclip_proj", "/glade/campaign/collections/rda/data/d651009", "BRCP85C5", "RCP8.5"},
}

type variable struct {
	short       string // request variable name
	fileName    string // name in the file and file name
	description string
}

var variables = []variable{
	{"u850", "U850", "850-hPa eastward wind"},
	{"v850", "V850", "850-hPa northward wind"},
	{"u700", "U700", "700-hPa eastward wind"},
	{"v700", "V700", "700-hPa northward wind"},
	{"u500", "U500", "500-hPa eastward wind"},
	{"v500", "V500", "500-hPa northward wind"},
}

func findCase(p period, member string) (string, error) {
	pattern := filepath.Join(p.root, "*"+p.compset+"*."+member)
	matches, err := filepath.Glob(pattern)
	if err != nil {
		return "", err
	}
	if len(matches) != 1 {
		return "", fmt.Errorf("%s member .%s: expected 1 case directory matching %s, found %d: %v",
			p.label, member, pattern, len(matches), matches)
	}
	return filepath.Base(matches[0]), nil
}

func writeEntry(b *strings.Builder, p period, member, caseName string, v variable) {
	name := p.datasetPrefix + "_" + member + "_" + v.short
	fmt.Fprintf(b, "\n[datasets.%s]\n", name)
	fmt.Fprintf(b, "description = \"MESACLIP %s %s, 6-hourly, member .%s\"\n", p.label, v.description, member)
	fmt.Fprintf(b, "archive = \"%s\"\n", p.archive)
	fmt.Fprintf(b, "layout = \"cesm_case\"\n")
	fmt.Fprintf(b, "case = \"%s\"\n", caseName)
	fmt.Fprintf(b, "stream = \"hour_6\"\n")
	fmt.Fprintf(b, `file_pattern = '\.cam\.h2\.%s\.(?P<key>(?P<year>\d{4})010100)-'`+"\n", v.fileName)
	fmt.Fprintf(b, "ops = [\"-selhour,{hours}\", \"-selmon,11,12,1,2,3\", \"-sellonlatbox,{box}\",\n")
	fmt.Fprintf(b, "       \"-setgrid,%s\", \"-selname,%s\"]\n", gridFile, v.fileName)
}

func main() {
	members := os.Args[1:]
	if len(members) == 0 {
		fmt.Fprintln(os.Stderr, "usage: go run gen_mesaclip_entries.go 004 005 ... > mesaclip_entries.toml")
		os.Exit(2)
	}

	var b strings.Builder
	b.WriteString("\n# ==== GENERATED by gen_mesaclip_entries.go: temporary until requests carry `case` ====\n")
	for _, member := range members {
		for _, p := range periods {
			caseName, err := findCase(p, member)
			if err != nil {
				fmt.Fprintln(os.Stderr, err)
				os.Exit(1)
			}
			fmt.Fprintf(&b, "\n# ---- MESACLIP %s, member .%s (%s) ----\n", p.label, member, caseName)
			for _, v := range variables {
				writeEntry(&b, p, member, caseName, v)
			}
		}
	}
	fmt.Print(b.String())
}
